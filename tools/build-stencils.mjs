// Extract the device stencils RSCanvas draws on wall tiles.
//
//   node tools/build-stencils.mjs [path-to-crosscanvas/devices.js]
//
// PROVENANCE IS CLASSIFIED FROM THE ARTWORK, not asserted in a comment.
//
// CrossCanvas's bundle mixes TWO icon sets, which the operator flagged and
// this script now proves per icon rather than taking on trust:
//
//   * Affinity (github.com/ecceman/affinity) - UNLICENSE, public domain, no
//     attribution required. Filled paths, `fill:rgb(45,103,185)`.
//   * Tabler (tabler.io/icons) - MIT, which DOES require the copyright and
//     permission notice to travel with the work. 24x24 stroke icons, scaled
//     into the 300px frame, `stroke="rgb(45,103,185)"`, round caps.
//
// Of the nine names guessStencil can produce, VM and UPS are Tabler and the
// rest are Affinity - so NOTICE-ICONS.md carries the MIT notice, and this
// script fails loudly if an icon matches neither signature, because an
// unattributable third set arriving silently is exactly the kind of thing
// that is discovered by a lawyer rather than by a build.
//
// TRANSFORMS, all mechanical:
//
//   1. XML declaration and DOCTYPE come off - legal standalone, noise inline.
//   2. The frame blue becomes currentColor in BOTH forms it appears in:
//      `fill:rgb(45,103,185)` (Affinity, CSS style) and
//      `stroke="rgb(45,103,185)"` (Tabler, attribute). Missing the second
//      form is a real bug this script shipped once: the two Tabler icons
//      rendered fixed blue on every theme while the other seven recoloured.
//
// Re-run it if the upstream set changes; the output is committed so a build
// never needs the parent repo present.

import fs from 'node:fs';
import path from 'node:path';

const SRC = process.argv[2] ?? 'C:/Workspace/crosscanvas/devices.js';
const OUT = path.join(import.meta.dirname, '..', 'public', 'stencils.js');

// guessStencil's vocabulary on the left, CrossCanvas's stencil name on the
// right. Verified by importing into a real CrossCanvas when stencil.ts was
// written - see the provenance note there.
const WANT = {
    firewall: 'Firewall',
    switch: 'Switch',
    router: 'Router',
    server: 'Server',
    nas: 'NAS',
    ups: 'UPS',
    vm: 'VM',
    storage: 'Storage',
    'access point': 'WifiAP',
    // Slice 35: the default for ping-only devices - an internet handoff or
    // an ISP has no agent to describe itself, so nothing can be guessed and
    // a globe is the honest picture of "something out there".
    globe: 'Globe',
};

const raw = fs.readFileSync(SRC, 'utf8');
const devices = JSON.parse(
    raw.replace(/^window\.BUNDLED_DEVICES\s*=\s*/, '').replace(/;\s*$/, ''),
);

const BRAND = /rgb\(\s*45\s*,\s*103\s*,\s*185\s*\)/g;

const out = {};
const origin = {};
let missing = 0;
let unknown = 0;
for (const [key, name] of Object.entries(WANT)) {
    const d = devices.find((x) => x.name === name);
    if (d === undefined) { console.log(`  MISSING ${name}`); missing++; continue; }
    let svg = Buffer.from(d.image.split(',')[1], 'base64').toString('utf8');

    // CLASSIFY BEFORE TRANSFORMING, while the signatures are still intact.
    const filled = /fill:\s*rgb\(\s*45\s*,\s*103\s*,\s*185\s*\)/.test(svg);
    const stroked = /stroke="rgb\(\s*45\s*,\s*103\s*,\s*185\s*\)"/.test(svg);
    const set = stroked ? 'Tabler (MIT)' : filled ? 'Affinity (Unlicense)' : 'UNKNOWN';
    if (set === 'UNKNOWN') unknown++;
    origin[key] = set;

    svg = svg
        .replace(/<\?xml[^>]*\?>\s*/g, '')
        .replace(/<!DOCTYPE[^>]*>\s*/g, '')
        // Both colour forms, in one pass over the brand blue wherever it
        // appears - CSS property or presentation attribute.
        .replace(BRAND, 'currentColor')
        // width/height 100% would fill the tile; the wall sizes these itself.
        .replace(/\swidth="100%"/, '')
        .replace(/\sheight="100%"/, '')
        .replace(/\s+/g, ' ')
        .trim();

    // THE CHECK THAT MAKES THE TRANSFORM HONEST: after rewriting, an icon
    // that still names a fixed colour cannot follow the theme, and would
    // sit in CrossCanvas blue on an amber wall forever. Loud, not silent.
    const stuck = svg.match(/(fill|stroke)\s*[:=]\s*"?(rgb\([^)]*\)|#[0-9a-fA-F]{3,6})/g);
    out[key] = svg;
    console.log(`  ${key.padEnd(13)} ${String(svg.length).padStart(5)} bytes  ${set.padEnd(22)}`
        + `${svg.includes('currentColor') ? 'themed' : 'NOT THEMED'}`
        + (stuck ? `  STUCK COLOURS: ${[...new Set(stuck)].join(' ')}` : ''));
    if (stuck) unknown++;
}

const bySet = {};
for (const [k, v] of Object.entries(origin)) (bySet[v] ??= []).push(k);

const body = `// GENERATED by tools/build-stencils.mjs - do not edit by hand.
//
// Device-type icons for wall tiles, keyed by guessStencil's vocabulary.
// Every colour is rewritten to currentColor, so an icon takes the wall's
// theme rather than shipping one palette.
//
// PROVENANCE (classified from the artwork by the generator, not asserted):
${Object.entries(bySet).map(([set, keys]) => `//   ${set}: ${keys.join(', ')}`).join('\n')}
//
// The MIT set requires its notice to travel with it - see NOTICE-ICONS.md.
window.Stencils = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(OUT, body);
console.log(`\nwrote ${OUT} - ${Object.keys(out).length} stencils, ${body.length} bytes`
    + `${missing > 0 ? `, ${missing} MISSING` : ''}`);
for (const [set, keys] of Object.entries(bySet)) console.log(`  ${set}: ${keys.join(', ')}`);
if (unknown > 0) {
    console.log('\nREFUSING: an icon matched no known set, or kept a fixed colour after the '
        + 'rewrite. Both mean the assumptions in this file no longer hold - fix them here '
        + 'rather than letting unattributable or unthemeable artwork into the build.');
    process.exit(1);
}
